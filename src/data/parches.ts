import type { Accesibilidad, Horario, Parche } from '../types'

type ClaveAcceso = keyof Accesibilidad

/** Devuelve un objeto de accesibilidad con las claves indicadas en true. */
function acceso(...activas: ClaveAcceso[]): Accesibilidad {
  return {
    movilidadReducida: activas.includes('movilidadReducida'),
    cercaAlMetro: activas.includes('cercaAlMetro'),
    aptoNinos: activas.includes('aptoNinos'),
    petFriendly: activas.includes('petFriendly'),
    lgbtiqFriendly: activas.includes('lgbtiqFriendly'),
    sinAlcohol: activas.includes('sinAlcohol'),
  }
}

/** Mismo horario los siete dias. */
function todosLosDias(abre: string, cierra: string): Horario[] {
  return [0, 1, 2, 3, 4, 5, 6].map((dia) => ({ dia, abre, cierra }) as Horario)
}

/** Horario solo en los dias indicados (0 = domingo). */
function dias(lista: Horario['dia'][], abre: string, cierra: string): Horario[] {
  return lista.map((dia) => ({ dia, abre, cierra }))
}

/** Espacio publico sin puertas: abierto a cualquier hora. */
function siempreAbierto(): Horario[] {
  return todosLosDias('00:00', '23:59')
}

